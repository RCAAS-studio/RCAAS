// Phone-size copies of the public site's photos: <name>-640w.webp and -960w.webp
// beside each original under public/assets/images, and src/features/marketing/
// data/imageSizes.ts (original widths) for srcSetFor(). Rerun after adding or
// replacing a photo: node scripts/image-variants.mjs
import sharp from 'sharp';
import { readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = 'public/assets/images';
const WIDTHS = [640, 960];
const variant = /-\d+w\.webp$/;
const sizes = {};
async function walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { await walk(full); continue; }
    if (!/\.(webp|jpe?g|png)$/i.test(e.name) || variant.test(e.name)) continue;
    const { width } = await sharp(full).metadata();
    const web = '/' + path.relative('public', full).split(path.sep).join('/');
    sizes[web] = width;
    for (const w of WIDTHS.filter((w) => w < width)) {
      const out = full.replace(/\.(webp|jpe?g|png)$/i, `-${w}w.webp`);
      const done = await stat(out).catch(() => null);
      if (done && done.mtimeMs >= (await stat(full)).mtimeMs) continue;
      await sharp(full).resize({ width: w }).webp({ quality: 78 }).toFile(out);
    }
  }
}
await walk(ROOT);
const keys = Object.keys(sizes).sort();
await writeFile('src/features/marketing/data/imageSizes.ts',
  `// Generated by scripts/image-variants.mjs: each photo's original width.\nexport const IMAGE_WIDTHS: Record<string, number> = {\n${keys.map((k) => `  ${JSON.stringify(k)}: ${sizes[k]},`).join('\n')}\n};\nexport const VARIANT_WIDTHS = ${JSON.stringify(WIDTHS)};\n`);
console.log(`[images] ${keys.length} photos, copies at ${WIDTHS.join(' and ')} px`);
